"""Build an offline UI font from the pinned component CBIN and actual UI text.

Outputs belong in the build directory. No font download or vendor mutation.
Fail on missing glyphs so new Chinese UI strings cannot silently disappear.
"""
import argparse
import base64
import importlib.util
from pathlib import Path
import re


def generate(fonts, source, output):
    provider = fonts / "scripts/glyph_provider.py"
    spec = importlib.util.spec_from_file_location("pinned_cbin_provider", provider)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    font = module.CbinFont.from_file(fonts / "cbin/font_noto_sans_common_16_4.bin")
    font.assert_wire_compatible()
    text = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', source.read_text(encoding="utf8")))
    codepoints = sorted(set(range(32, 127)) | {ord(c) for c in text if ord(c) >= 32})
    glyphs = [font.glyph(c) for c in codepoints]
    missing = [chr(c) for c, glyph in zip(codepoints, glyphs) if glyph is None]
    if missing:
        raise ValueError("UI font missing codepoints: " + repr(missing))
    if len(glyphs) > 512 or codepoints[-1] - 32 > 65534:
        raise ValueError("UI font exceeds fixed glyph/cmap budget")
    bitmap = bytearray()
    descriptors = ["{.bitmap_index=0,.adv_w=0,.box_w=0,.box_h=0,.ofs_x=0,.ofs_y=0}"]
    for glyph in glyphs:
        descriptors.append("{.bitmap_index=%d,.adv_w=%d,.box_w=%d,.box_h=%d,.ofs_x=%d,.ofs_y=%d}" % (
            len(bitmap), glyph["adv_w"], glyph["box_w"], glyph["box_h"], glyph["ofs_x"], glyph["ofs_y"]))
        bitmap.extend(base64.b64decode(glyph["bitmap"]))
    if len(bitmap) > 64 * 1024:
        raise ValueError("UI font bitmap exceeds 64 KiB")
    result = ['// Generated by scripts/generate_phone_ui_font.py; do not edit.', '#include <lvgl.h>',
              'static const uint8_t bitmaps[] = {', ','.join(map(str, bitmap)), '};',
              'static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {', ',\n'.join(descriptors), '};',
              'static const uint16_t unicode[] = {', ','.join(str(c - 32) for c in codepoints), '};',
              'static const lv_font_fmt_txt_cmap_t cmap[] = {{',
              f'.range_start=32,.range_length={codepoints[-1] - 31},.glyph_id_start=1,',
              f'.unicode_list=unicode,.glyph_id_ofs_list=nullptr,.list_length={len(glyphs)},',
              '.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};',
              'static const lv_font_fmt_txt_dsc_t descriptor = {',
              '.glyph_bitmap=bitmaps,.glyph_dsc=glyphs,.cmaps=cmap,.kern_dsc=nullptr,',
              '.kern_scale=0,.cmap_num=1,.bpp=4,.kern_classes=0,.bitmap_format=0};',
              'extern const lv_font_t phone_settings_font = {',
              '.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
              f'.line_height={font.line_height},.base_line={font.base_line},',
              '.subpx=LV_FONT_SUBPX_NONE,.underline_position=-2,.underline_thickness=1,',
              '.dsc=&descriptor,.fallback=nullptr,.user_data=nullptr};', '']
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(result), encoding="utf8")
    print(f"Phone UI font: {len(glyphs)} glyphs, {len(bitmap)} bitmap bytes; all UI strings covered")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fonts", required=True, type=Path)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    generate(args.fonts, args.source, args.output)
